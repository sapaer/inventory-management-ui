/**
 * Resolve UI copy. Prefer `t("key")`.
 * Still accepts legacy `t(lang, "key")` so existing call sites keep working.
 */
export function t(a, b, ...rest) {
  const legacy = typeof b === "string" && (a === "en" || a === "hi");
  const key = legacy ? b : a;
  const args = legacy ? rest : b !== undefined ? [b, ...rest] : [];
  const value = messages[key] ?? key;
  return typeof value === "function" ? value(...args) : value;
}

